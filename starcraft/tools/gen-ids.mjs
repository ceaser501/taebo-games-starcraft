// Writes js/bw-ids.js (unit, order, tech and upgrade numbers) from OpenBW's bwenums.h, so the page
// uses the same ids as the engine.
//
//   node starcraft/tools/gen-ids.mjs
import fs from 'node:fs';
import path from 'node:path';

const dir = path.dirname(new URL(import.meta.url).pathname);
const src = fs.readFileSync(path.join(dir, '../engine/openbw/bwenums.h'), 'utf8');
const out = ['// Generated by tools/gen-ids.mjs from engine/openbw/bwenums.h. Do not edit.'];
for (const name of ['UnitTypes', 'Orders', 'TechTypes', 'UpgradeTypes']) {
  const body = src.match(new RegExp(`enum struct ${name}[^{]*\\{([\\s\\S]*?)\\};`))[1];
  const ids = {};
  let next = 0;
  for (const raw of body.split(',')) {
    const item = raw.replace(/\/\/.*$/gm, '').trim();
    if (!item) continue;
    const [key, value] = item.split('=').map((s) => s.trim());
    next = value != null ? Number(value) : next;
    ids[key] = next++;
  }
  out.push(`export const ${name} = ${JSON.stringify(ids)};`);
}
fs.writeFileSync(path.join(dir, '../js/bw-ids.js'), out.join('\n') + '\n');
console.log('wrote js/bw-ids.js');
